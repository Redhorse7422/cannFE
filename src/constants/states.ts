// Helper function to get state label by value
export const getStateLabelByValue = (value: string): string => {
  const foundState = US_STATES.find((state) => state.value === value)
  return foundState ? foundState.label : value
}

// Helper function to get state value by label
export const getStateValueByLabel = (label: string): string => {
  const foundState = US_STATES.find((state) => state.label === label)
  return foundState ? foundState.value : label
}
